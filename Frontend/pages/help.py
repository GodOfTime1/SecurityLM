"""Reviewed support guide, API-backed model advice, and honest connection status."""
import streamlit as st
from api_client import APIError, resource
from help_content import TOPICS, guide_answer, bounded_selector_history
from ui_common import connect, setup, show_notice, get_assistants, pick_assistant, existing_page

setup("Help & model advisor")
api,user=connect()
show_notice()
st.caption("SECURITYLM / SUPPORT")
st.title("Help & model advisor")
st.write("Get setup answers, choose a supported model, and see what is actually connected.")


def read_status(path, **kwargs):
    try:
        return api.request('GET',path,**kwargs)
    except APIError as exc:
        return {'state':'unavailable','can_request_advice':False,'message':str(exc),
                'setup_message':'This status service is unavailable. Check your backend version and connection.'}


try:
    assistants=get_assistants(api)
except APIError:
    assistants=[]
assistant=pick_assistant(assistants,key='help_profile') if assistants else None
advisor=read_status('/model-selector/status')
params={'assistant_id':assistant['id']} if assistant else {}
runtime=read_status('/runtime/status',params=params)

guide_tab,advisor_tab,status_tab=st.tabs(['Quick help','Model advisor','Connection checks'])

with guide_tab:
    st.subheader('A quick answer, without the guesswork')
    st.caption('Reviewed product documentation · these guide replies are not generated by a language model.')
    selected=None
    for col,key in zip(st.columns(4),['slm','privacy','hardware','setup']):
        if col.button(TOPICS[key][0],key='faq_'+key,use_container_width=True):
            selected=key
    with st.form('guide_question',clear_on_submit=True):
        question=st.text_input('Ask about setup, privacy, documents, or hardware',max_chars=2000)
        ask=st.form_submit_button('Find a guide answer')
    if selected:
        title,answer=TOPICS[selected]
        messages=st.session_state.get('help_guide_messages',[])
        st.session_state['help_guide_messages']=(messages+[
            {'role':'user','content':title},{'role':'assistant','content':answer}])[-12:]
    elif ask and question.strip():
        title,answer=guide_answer(question)
        messages=st.session_state.get('help_guide_messages',[])
        st.session_state['help_guide_messages']=(messages+[
            {'role':'user','content':question},{'role':'assistant','content':title+'\n\n'+answer}])[-12:]
    for message in st.session_state.get('help_guide_messages',[]):
        with st.chat_message(message['role']):
            st.text(message['content'])
    with st.expander('All guide topics'):
        for title,answer in TOPICS.values():
            st.subheader(title)
            st.text(answer)
    if st.button('Clear guide conversation'):
        st.session_state.pop('help_guide_messages',None)
        st.rerun()

with advisor_tab:
    st.subheader('Find a model for your use case')
    state=advisor.get('state','unavailable')
    if state=='demo':
        st.warning('DEMO ADVISOR · Uses explicit filters, not an LLM. Fill in the requirements below.')
    elif state=='configured':
        st.info('LIVE ADAPTER CONFIGURED · Connectivity and output quality are checked when you ask for advice.')
    else:
        st.info(advisor.get('setup_message','The advisor is not ready.'))
    st.caption('This sends your advisor messages, recent advisor history, and public catalog metadata. Uploaded company documents are not retrieved by this workflow.')
    count=advisor.get('active_catalog_count')
    if count==0:
        st.info('No active catalog entries are available. An administrator can configure presets in Model settings.')
    if st.button('Start new advisor conversation'):
        for key in ['advisor_messages','advisor_last','advisor_requirements','advisor_error']:
            st.session_state.pop(key,None)
        st.session_state['advisor_revision']=st.session_state.get('advisor_revision',0)+1
        st.rerun()

    req=st.session_state.get('advisor_requirements',{})
    revision=st.session_state.get('advisor_revision',0)
    prefix='advisor_'+str(revision)+'_'
    with st.expander('Your requirements',expanded=state=='demo'):
        left,right=st.columns(2)
        tasks=[None,'document_qa','coding','summarization','general']
        task_names={None:'Let the advisor interpret','document_qa':'Document Q&A','coding':'Coding',
                    'summarization':'Summarization','general':'General help'}
        task=left.selectbox('Task',tasks,index=tasks.index(req.get('task')) if req.get('task') in tasks else 0,
                            format_func=lambda value:task_names[value],key=prefix+'task')
        deployments=[None,'local','remote','either']
        deployment=right.selectbox('Deployment',deployments,index=deployments.index(req.get('deployment')) if req.get('deployment') in deployments else 0,
            format_func=lambda value:'Let the advisor interpret' if value is None else value.title(),key=prefix+'deployment')
        specify=st.checkbox('Specify memory budget',value=req.get('available_memory_gb') is not None,key=prefix+'specify')
        memory=st.number_input('Usable model memory (GB)',min_value=0.1,max_value=100000.0,
            value=float(req.get('available_memory_gb') or 8),disabled=not specify,key=prefix+'memory')
        st.caption('RAM and VRAM are different resources. This is a simplified budget; the actual build must be measured.')
        tools_options=[None,True,False]
        needs_tools=st.selectbox('Needs tool support',tools_options,index=tools_options.index(req.get('needs_tools')),
            format_func=lambda value:'No preference' if value is None else ('Yes' if value else 'No'),key=prefix+'tools')
        language=st.text_input('Language (optional)',value=req.get('language') or '',max_chars=40,key=prefix+'language')
        priorities=['balanced','speed','quality']
        priority=st.selectbox('Priority',priorities,index=priorities.index(req.get('priority')) if req.get('priority') in priorities else 0,key=prefix+'priority')
        ready_only=st.checkbox('Only models marked ready',value=bool(req.get('ready_only')),key=prefix+'ready')

    for message in st.session_state.get('advisor_messages',[]):
        with st.chat_message(message['role']):
            st.text(message['content'])
    if st.session_state.get('advisor_error'):
        st.error(st.session_state['advisor_error'])
    can_ask=bool(advisor.get('can_request_advice'))
    with st.form('advisor_question_'+str(revision)):
        message=st.text_area('Describe what you need',placeholder='I need an assistant to answer questions from our IT manuals.',max_chars=2000)
        send=st.form_submit_button('Ask model advisor',type='primary',disabled=not can_ask)
    if send:
        if not message.strip():
            st.warning('Describe your use case first.')
        else:
            requirements={'task':task,'deployment':deployment,'available_memory_gb':memory if specify else None,
                'needs_tools':needs_tools,'language':language.strip() or None,'priority':priority,'ready_only':ready_only}
            requirements={k:v for k,v in requirements.items() if v is not None}
            try:
                with st.spinner('Checking the supported catalog…'):
                    response=api.request('POST','/model-selector/chat',json={'message':message,'requirements':requirements,
                        'history':bounded_selector_history(st.session_state.get('advisor_messages',[]))})
                if (not isinstance(response,dict) or not isinstance(response.get('answer'),str)
                        or not isinstance(response.get('requirements'),dict) or not isinstance(response.get('recommendations'),list)):
                    raise APIError('The advisor returned an unexpected response.')
            except APIError as exc:
                # Stateless advice has no tool effects; failed calls do not append a fake reply.
                st.session_state['advisor_error']=str(exc)
                st.error(str(exc))
            else:
                messages=st.session_state.get('advisor_messages',[])
                st.session_state['advisor_messages']=(messages+[
                    {'role':'user','content':message},{'role':'assistant','content':response['answer']}])[-12:]
                st.session_state['advisor_last']=response
                st.session_state['advisor_requirements']=response['requirements']
                st.session_state.pop('advisor_error',None)
                st.session_state['advisor_revision']=revision+1
                st.rerun()

    result=st.session_state.get('advisor_last')
    if result:
        st.caption('Last advice mode: '+{'demo':'Demo filters','rules':'Catalog rules','llm':'Language-model advice'}.get(result.get('mode'),'Unknown'))
        for warning in result.get('warnings',[]):
            st.text(warning)
        for follow_up in result.get('follow_up_questions',[]):
            st.text('Follow-up: '+follow_up)
        with st.expander('Requirements used for this advice — review before applying'):
            st.json(result['requirements'])
        if result.get('status')=='no_match':
            st.info('A hard memory limit excludes local entries with unknown estimates. Preset target budgets are not measured requirements; ask the model teammate to verify catalog facts.')
        for model in result['recommendations']:
            with st.container(border=True):
                st.subheader(model['name'])
                st.text(model.get('description',''))
                st.caption('Marked ready by admin' if model.get('ready') else 'Needs runtime setup')
                if user['role']=='admin' and assistant:
                    if st.button('Apply to '+assistant['name'],key='advisor_apply_'+model['id']):
                        try:
                            api.request('POST','/model-selector/apply',json={'assistant_id':assistant['id'],
                                'model_id':model['id'],'catalog_version':model['version'],'expected_current_model':assistant['model']})
                        except APIError as exc:
                            st.error(str(exc))
                        else:
                            st.session_state['notice']='Model choice saved to the selected profile. This does not install or start a model. Start a new workspace conversation after switching.'
                            st.rerun()
                else:
                    st.caption('An administrator can apply this choice after selecting an assistant profile.')

with status_tab:
    st.subheader('See which part is ready')
    st.table([
        {'Component':'Backend access','State':'Authenticated','Meaning':'Your individual credential was accepted by /me.'},
        {'Component':'Document chat','State':runtime.get('state','unknown'),'Meaning':runtime.get('message','Status not available.')},
        {'Component':'Model advisor','State':advisor.get('state','unknown'),'Meaning':advisor.get('setup_message','Status not available.')},
    ])
    st.caption('Document chat and the advisor use independent model configurations. A configured state is not a completed connectivity or quality test.')
    if st.button('Refresh connection status'):
        st.rerun()
    if user['role']=='admin' and assistant:
        if st.button('Check document runtime'):
            try:
                with st.spinner('Checking the selected document runtime…'):
                    check=api.request('POST','/runtime/check',json={'assistant_id':assistant['id']})
            except APIError as exc:
                st.error(str(exc))
            else:
                (st.success if check.get('available') else st.warning)(check.get('message','No status returned.'))
        if existing_page('pages/model_settings.py'):
            st.page_link('pages/model_settings.py',label='Open model settings',icon='⚙️')
    st.page_link('home.py',label='Return to workspace',icon='💬')
